import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{window.walletRequests=[];window.ethereum={request:async p=>{window.walletRequests.push(p.method);throw Error('NO REAL WALLET IN TEST');},on:()=>{},removeListener:()=>{}};});
await page.goto('http://127.0.0.1:3000');
await page.getByRole('heading',{name:'Your Bitcoin. Accounted for.'}).waitFor();
assert.match(await page.locator('.big-amount').innerText(),/0.01842/);
await page.screenshot({path:'screenshots/desktop.png',fullPage:true});
await page.getByRole('button',{name:'Start example recovery',exact:true}).click();
await page.getByRole('heading',{name:'Recover remaining collateral',exact:true}).waitFor();
await page.getByRole('button',{name:'Simulate example claim',exact:true}).click();
await page.getByText('Example simulation illustrated',{exact:true}).waitFor();
const complete=page.getByRole('button',{name:'Complete example recovery',exact:true});
assert.equal(await complete.isDisabled(),true);
await page.getByLabel('I understand these are fictional funds.').check();
await page.getByLabel('I understand no real transaction will be sent.').check();
await complete.click();
await page.getByRole('heading',{name:'Walkthrough complete.',exact:true}).waitFor();
assert.deepEqual(await page.evaluate(()=>window.walletRequests),[]);
await page.screenshot({path:'screenshots/recovery-demo.png',fullPage:true});
await page.getByRole('button',{name:'Overview',exact:true}).click();
await page.getByLabel('Example scenario').selectOption('liquidated');
await page.getByRole('heading',{name:'Liquidation is not redemption.'}).waitFor();
await page.getByRole('button',{name:'Evidence & records'}).click();
await page.getByRole('heading',{name:'What this snapshot actually tells us'}).waitFor();
await page.getByRole('button',{name:'Live wallet',exact:true}).click();
await page.getByLabel('Public wallet address').fill('not-a-wallet');
await page.getByRole('button',{name:'Check wallet',exact:true}).click();await page.getByRole('alert').waitFor();
await page.getByLabel('Public wallet address').fill('0x0000000000000000000000000000000000000000');
await page.getByRole('button',{name:'Check wallet',exact:true}).click();
await page.getByText('Mainnet snapshot',{exact:true}).waitFor({timeout:60000});
assert.match(await page.locator('.loan-status').innerText(),/No loan on record/);
await page.getByRole('button',{name:'Preview recovery',exact:true}).click();
await page.getByText('MAINNET · SIMULATION ONLY',{exact:true}).waitFor();
assert.equal(await page.getByRole('button',{name:'Simulate claim',exact:true}).isDisabled(),true);
const config=await (await page.request.get('http://127.0.0.1:3000/api/config')).json();assert.equal(config.claimsEnabled,false);
const preview=await page.request.get('http://127.0.0.1:3000/api/claim/preview/0x0000000000000000000000000000000000000000');assert.equal(preview.status(),200);assert.equal((await preview.json()).eligible,false);
assert.equal(await page.locator('body').evaluate(el=>el.scrollWidth>innerWidth),false);
await page.getByRole('button',{name:'How it works',exact:true}).click();
await page.getByRole('dialog').waitFor();await page.keyboard.press('Escape');assert.equal(await page.getByRole('dialog').count(),0);
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Try a walkthrough',exact:true}).click();await page.getByLabel('Example scenario').selectOption('redeemed');
await page.getByRole('button',{name:'Toggle navigation'}).click();await page.getByRole('button',{name:'Overview',exact:true}).click();
await page.screenshot({path:'screenshots/mobile.png',fullPage:true});
await page.getByRole('button',{name:'Start example recovery',exact:true}).click();
await page.getByRole('button',{name:'Simulate example claim',exact:true}).click();
await page.screenshot({path:'screenshots/recovery-mobile.png',fullPage:true});
assert.equal(await page.locator('body').evaluate(el=>el.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
assert.equal((await page.request.get('http://127.0.0.1:3000/api/inspect/not-an-address')).status(),400);
console.log('PASS: production desktop/mobile, complete no-wallet demo, consent gates, mainnet address reads, ineligible claim, signing-off configuration, dialog Escape, no JS errors or overflow.');
await browser.close();
